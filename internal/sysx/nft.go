// forwardComment tags every rule the agent inserts into a chain it does not
// own, so it can find them again to remove them.
const forwardComment = "failover"

// egressForwardComment marks the exception for backend-originated traffic, so
// that toggling that feature off leaves the published exceptions in place.
const egressForwardComment = "failover_egress"

// commentNeedle renders how nft prints a comment, so that searching for one
// cannot match another that merely starts with the same text - "failover" is a
// prefix of "failover_egress", and matching loosely would have the published
// exceptions and the egress one delete each other.
func commentNeedle(comment string) string { return `comment "` + comment + `"` }

// DockerUserChain is Docker's documented extension point: a chain jumped from
// FORWARD before its own rules, which Docker never flushes.
const DockerUserChain = "DOCKER-USER"

// EnsureForwardExceptions lets published traffic cross the frontend when
// something else owns a drop-policy forward chain.
//
// Docker sets the filter table's FORWARD policy to drop. Published traffic is
// DNAT'd and therefore forwarded, and nftables gives no way to override that
// from another table: an accept is only final for the chain it appears in,
// while a drop is final everywhere. The agent's own table cannot rescue the
// packet, so the exceptions have to go into the chain Docker leaves for
// exactly this purpose.
//
// Matching is by connection state plus destination, never by source address:
// a reply has its source rewritten back to the public address before the
// forward hook sees it, so a source match silently never fires.
//
// Does nothing when no such chain exists, which is the common case.
// The destination is the overlay data prefix rather than the backend's address
// alone, so a service published to a linker crosses the frontend on the same
// exception. Where no linkers are configured that prefix is the backend's /32
// and the rule is unchanged.
func EnsureForwardExceptions(ctx context.Context, r Runner, dataPrefix string) error {
	existing, err := r.Run(ctx, "nft", "-a", "list", "chain", "ip", "filter", DockerUserChain)
	if err != nil {
		return nil // no Docker, nothing to work around
	}

	// Checked against the prefix, not merely against the comment. Skipping on
	// the comment alone meant the rule was written once and never revisited:
	// setting overlay.subnet later widened the route and the egress NAT but
	// left this accept pinned to the backend's /32, so a service published to
	// a linker was DNAT'd correctly and then dropped by the forward policy on
	// the way out. Nothing reported it - a drop is a timeout, which reads as
	// the far host being down.
	dropStaleForwardRules(ctx, r, existing, forwardComment, "daddr", dataPrefix)

	rules := [][]string{
		{"ip", "daddr", dataPrefix, "accept"},
		{"ct", "state", "established,related", "accept"},
	}
	for _, rule := range rules {
		if hasForwardRule(existing, forwardComment, rule) {
			continue
		}
		args := append([]string{"insert", "rule", "ip", "filter", DockerUserChain}, rule...)
		args = append(args, "comment", fmt.Sprintf("%q", forwardComment))
		if _, err := r.Run(ctx, "nft", args...); err != nil {
			return fmt.Errorf("insert forward exception: %w", err)
		}
	}
	return nil
}

// hasForwardRule reports whether a chain listing already carries this exact
// rule under our comment.
func hasForwardRule(listing, comment string, rule []string) bool {
	needle := strings.Join(rule, " ")
	for _, line := range strings.Split(listing, "\n") {
		if !strings.Contains(line, commentNeedle(comment)) {
			continue
		}
		if strings.Contains(line, needle) {
			return true
		}
	}
	return false
}

// dropStaleForwardRules removes rules of ours that match on the given address
// field with a prefix we no longer want.
//
// Deleting by handle rather than rewriting the chain, because DOCKER-USER is
// not ours: an operator's own rules live there too, and flushing it to reassert
// two of our own would take theirs with it.
func dropStaleForwardRules(ctx context.Context, r Runner, listing, comment, field, want string) {
	for _, line := range strings.Split(listing, "\n") {
		if !strings.Contains(line, commentNeedle(comment)) || !strings.Contains(line, " "+field+" ") {
			continue
		}
		if strings.Contains(line, " "+field+" "+want+" ") {
			continue // already the prefix we want
		}
		i := strings.LastIndex(line, "# handle ")
		if i < 0 {
			continue
		}
		handle := strings.TrimSpace(line[i+len("# handle "):])
		_, _ = r.Run(ctx, "nft", "delete", "rule", "ip", "filter", DockerUserChain, "handle", handle)
	}
}

// EnsureEgressForwardException lets a connection the backend originates cross
// the forward path.
//
// It is separate from EnsureForwardExceptions, and matches on source where that
// one deliberately does not, because it covers the opposite direction. Those
// rules cover traffic arriving for a published service, whose reply has its
// source rewritten back to the public address before the forward hook sees it,
// so a source match there would silently never fire. This is a connection going
// the other way: it is still carrying the overlay source address at the forward
// hook, and matches nothing the published rules cover - not `ip daddr backend`,
// because the destination is somewhere on the internet, and not `ct state
// established`, because it is the first packet of a new connection. Without it
// the source NAT is installed correctly and nothing ever reaches it.
//
// It carries its own comment so that toggling the feature off removes this and
// leaves the published exceptions alone.
func EnsureEgressForwardException(ctx context.Context, r Runner, dataPrefix string) error {
	existing, err := r.Run(ctx, "nft", "-a", "list", "chain", "ip", "filter", DockerUserChain)
	if err != nil {
		return nil // no Docker, nothing to work around
	}
	// Same reconciliation as the published exceptions, for the same reason:
	// widening the overlay has to widen what may leave by it, or a linker's
	// outbound traffic is dropped where the backend's is allowed.
	dropStaleForwardRules(ctx, r, existing, egressForwardComment, "saddr", dataPrefix)
	if hasForwardRule(existing, egressForwardComment, []string{"ip", "saddr", dataPrefix, "accept"}) {
		return nil
	}
	args := []string{"insert", "rule", "ip", "filter", DockerUserChain,
		"ip", "saddr", dataPrefix, "accept",
		"comment", fmt.Sprintf("%q", egressForwardComment)}
	if _, err := r.Run(ctx, "nft", args...); err != nil {
		return fmt.Errorf("insert egress forward exception: %w", err)
	}
	return nil
}

// RemoveEgressForwardException deletes the rule EnsureEgressForwardException
// added, and only that one.
func RemoveEgressForwardException(ctx context.Context, r Runner) {
	removeCommentedForwardRules(ctx, r, egressForwardComment)
}

// RemoveForwardExceptions deletes only the rules the agent inserted, found by
// their comment. Everything else in the chain belongs to somebody else.
func RemoveForwardExceptions(ctx context.Context, r Runner) {
	removeCommentedForwardRules(ctx, r, forwardComment)
}

// removeCommentedForwardRules deletes every rule in the chain carrying one
// comment, by handle. The comment is the only thing distinguishing the agent's
// rules from everyone else's in a chain it does not own.
func removeCommentedForwardRules(ctx context.Context, r Runner, comment string) {
	out, err := r.Run(ctx, "nft", "-a", "list", "chain", "ip", "filter", DockerUserChain)
	if err != nil {
		return
	}
	for _, line := range strings.Split(out, "\n") {
		if !strings.Contains(line, commentNeedle(comment)) {
			continue
		}
		i := strings.LastIndex(line, "# handle ")
		if i < 0 {
			continue
		}
		handle := strings.TrimSpace(line[i+len("# handle "):])
		_, _ = r.Run(ctx, "nft", "delete", "rule", "ip", "filter", DockerUserChain, "handle", handle)
	}
}

// ForwardIsBlocked reports whether some chain the agent does not own drops
// forwarded traffic by default, which silently breaks every published service.
func ForwardIsBlocked(ctx context.Context, r Runner) bool {
	out, err := r.Run(ctx, "nft", "list", "ruleset")
	if err != nil {
		return false
	}
	for _, line := range strings.Split(out, "\n") {
		if strings.Contains(line, "hook forward") && strings.Contains(line, "policy drop") {
			return true
		}
	}
	return false
}
