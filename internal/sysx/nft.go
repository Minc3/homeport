// NFTTable is the dedicated table the agent owns. Nothing else is touched, so
// removing every trace of this program is one command:
//
//	nft delete table ip failover
const NFTTable = "failover"

// NFTReturnTable is the backend's table. It carries no NAT of its own - only
// the connection marking that lets reply traffic find its way back out the
// tunnel it arrived on.
const NFTReturnTable = "failover_return"

// NFTEgressTable is the frontend's optional source-NAT table.
//
// It is a table of its own rather than a chain in NFTTable, and that separation
// is the point. NFTTable carries the published services and must never contain
// a masquerade - rewriting the source there would take the real client IP away
// from srcds and the web server, which is the reason the whole system routes
// instead of proxying, and `nft_test.go` asserts it. This table rewrites the
// source of traffic travelling the other way: connections the *backend*
// originates, where there is no client address to preserve because there is no
// client. Keeping them apart means the assertion on the published ruleset stays
// literally true, and this table can be added and removed on its own.
const NFTEgressTable = "failover_egress"

// ReturnMark stamps connections that arrived through a tunnel.
//
// The backend already routes replies by source address (ip rule from the
// overlay address), which is enough while the service listens on the host. It
// stops working the moment anything DNATs further - a container on a bridge
// network being the ordinary case - because the routing decision for the reply
// happens *before* its source is rewritten back to the overlay address. At that
// moment the packet still carries the container's address, matches no rule, and
// leaves by the default route instead of the tunnel.
//
// Marking the connection on the way in and restoring that mark on the way out
// routes by connection rather than by address, which survives any number of
// translations. 0x200 is clear of the path marks (0x101-0x103) and the control
// mark (0x100).
const ReturnMark = 0x200

// BuildRuleset renders the DNAT ruleset for the published services.
//
// Destination NAT only. There is deliberately no masquerade rule: leaving the
// source address alone is what makes the backend see the real client IP, for
// UDP as well as TCP, without any proxy in the path.
func BuildRuleset(cfg model.Config) string {
	var b strings.Builder
	b.WriteString("# generated by failover-frontend - do not edit by hand\n")
	b.WriteString("# destination NAT only; source addresses are never rewritten,\n")
	b.WriteString("# so srcds and the web server see real client IPs.\n\n")

	// Atomic replace: create-if-missing, delete, redefine.
	fmt.Fprintf(&b, "table ip %s\n", NFTTable)
	fmt.Fprintf(&b, "delete table ip %s\n\n", NFTTable)
	fmt.Fprintf(&b, "table ip %s {\n", NFTTable)
	b.WriteString("\tchain prerouting {\n")
	b.WriteString("\t\ttype nat hook prerouting priority dstnat; policy accept;\n")

	for _, s := range cfg.Services {
		if !s.Enabled {
			continue
		}
		proto := strings.ToLower(s.Proto)
		if proto != "tcp" && proto != "udp" {
			continue
		}
		port := fmt.Sprintf("%d", s.Port)
		if s.PortEnd > s.Port {
			port = fmt.Sprintf("%d-%d", s.Port, s.PortEnd)
		}
		var rule strings.Builder
		rule.WriteString("\t\t")
		if cfg.Frontend.PublicIface != "" {
			fmt.Fprintf(&rule, "iifname %q ", cfg.Frontend.PublicIface)
		}
		if cfg.Frontend.PublicIP != "" {
			fmt.Fprintf(&rule, "ip daddr %s ", cfg.Frontend.PublicIP)
		}
		// Almost always the backend. A service names a different overlay
		// address only where a linker agent publishes it from another host,
		// and the routing to get there is the same route widened by one
		// prefix - there is no second mechanism here.
		fmt.Fprintf(&rule, "%s dport %s dnat to %s comment %q\n",
			proto, port, s.TargetOr(cfg.Overlay.BackendIP), s.Name)
		b.WriteString(rule.String())
	}

	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return b.String()
}

// BuildEgressRuleset renders the frontend's source-NAT for backend-originated
// traffic, or "" when the feature is off.
//
// The match is narrow on purpose: the overlay source address, and the public
// interface as the way out. Only the backend can send from the overlay address,
// and restricting the output interface keeps it away from anything heading back
// down a tunnel - masquerading there would rewrite the source of a reply to a
// player, which is exactly what the rest of the design exists to avoid.
//
// A configured public IP produces an snat rather than a masquerade: it is one
// less address lookup per connection, and it fails visibly if the address is
// wrong instead of silently picking a different one.
func BuildEgressRuleset(cfg model.Config) string {
	if !cfg.Frontend.BackendEgress || cfg.Overlay.BackendIP == "" || cfg.Frontend.PublicIface == "" {
		return ""
	}
	var b strings.Builder
	b.WriteString("# generated by failover-frontend - do not edit by hand\n")
	b.WriteString("# gives traffic the backend originates the frontend's public\n")
	b.WriteString("# address, so a game server is listed at the published address\n")
	b.WriteString("# rather than at the house's own internet service.\n\n")

	fmt.Fprintf(&b, "table ip %s\n", NFTEgressTable)
	fmt.Fprintf(&b, "delete table ip %s\n\n", NFTEgressTable)
	fmt.Fprintf(&b, "table ip %s {\n", NFTEgressTable)
	b.WriteString("\tchain postrouting {\n")
	b.WriteString("\t\ttype nat hook postrouting priority srcnat; policy accept;\n")

	// The whole overlay range, so a linker's traffic is translated by the same
	// rule as the backend's. On a site with no linkers MatchPrefix is the
	// backend's own address and this renders exactly as it always did.
	fmt.Fprintf(&b, "\t\tip saddr %s oifname %q ", cfg.Overlay.MatchPrefix(), cfg.Frontend.PublicIface)
	if cfg.Frontend.PublicIP != "" {
		fmt.Fprintf(&b, "snat to %s\n", cfg.Frontend.PublicIP)
	} else {
		b.WriteString("masquerade\n")
	}

	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return b.String()
}

// ApplyEgressRuleset loads the frontend's source-NAT table.
func ApplyEgressRuleset(ctx context.Context, r Runner, stateDir, ruleset string) (string, error) {
	return applyRuleset(ctx, r, filepath.Join(stateDir, "egress.nft"), ruleset)
}

// RemoveEgressRuleset deletes the frontend's source-NAT table.
func RemoveEgressRuleset(ctx context.Context, r Runner) {
	_, _ = r.Run(ctx, "nft", "delete", "table", "ip", NFTEgressTable)
}

// EgressMark stamps traffic being pulled onto the tunnel from a backend-side
// network. Clear of the path marks (0x101-0x103), the control mark (0x100) and
// the return mark (0x200).
const EgressMark = 0x300

// BuildBackendEgressRuleset renders the backend half of the egress feature, or
// "" when no source networks are configured.
//
// Two rules, doing two different jobs:
//
// The prerouting mark is what redirects the traffic. A container's packets
// arrive at the host over its bridge and are forwarded, so the routing decision
// for them happens after this hook - setting the mark here is what makes
// `ip rule fwmark 0x300 lookup 100` send them down the active tunnel instead of
// out to pfSense. Table 100 is the return table, which already tracks the
// frontend's choice, so this follows failover with nothing extra to maintain.
//
// The postrouting SNAT rewrites the source to the overlay address, because that
// is what the frontend's own egress rule matches and what it can route a reply
// back to. Without it the packet arrives at the frontend carrying a private
// container address that nothing downstream knows how to answer.
//
// The SNAT priority is deliberately ahead of srcnat (100), which is where
// Docker installs its own masquerade. Left to run first, Docker would rewrite
// the source to an address on the output interface - and the tunnels carry no
// address at all, because wg-quick runs with Table = off and no Address.
func BuildBackendEgressRuleset(cidrs, ifaces []string, overlayIP string) string {
	if len(cidrs) == 0 || len(ifaces) == 0 || overlayIP == "" {
		return ""
	}
	set := func(items []string) string {
		quoted := make([]string, 0, len(items))
		for _, i := range items {
			quoted = append(quoted, fmt.Sprintf("%q", i))
		}
		return "{ " + strings.Join(quoted, ", ") + " }"
	}

	var b strings.Builder
	b.WriteString("# generated by failover-backend - do not edit by hand\n")
	b.WriteString("# pulls these networks onto the tunnel so their traffic leaves\n")
	b.WriteString("# by the frontend's public address rather than the house's.\n\n")

	fmt.Fprintf(&b, "table ip %s\n", NFTEgressTable)
	fmt.Fprintf(&b, "delete table ip %s\n\n", NFTEgressTable)
	fmt.Fprintf(&b, "table ip %s {\n", NFTEgressTable)

	b.WriteString("\tchain prerouting {\n")
	b.WriteString("\t\ttype filter hook prerouting priority mangle; policy accept;\n")
	for _, c := range cidrs {
		fmt.Fprintf(&b, "\t\tip saddr %s meta mark set %#x\n", c, EgressMark)
	}
	b.WriteString("\t}\n")

	// Ahead of Docker's masquerade at srcnat.
	b.WriteString("\tchain postrouting {\n")
	b.WriteString("\t\ttype nat hook postrouting priority -10; policy accept;\n")
	for _, c := range cidrs {
		fmt.Fprintf(&b, "\t\tip saddr %s oifname %s snat to %s\n", c, set(ifaces), overlayIP)
	}
	b.WriteString("\t}\n")

	b.WriteString("}\n")
	return b.String()
}

// BuildReturnRuleset renders the backend's connection-marking ruleset.
//
// Only the reply direction restores the mark. Restoring it for every packet
// looks equivalent and is not: the request arriving from a tunnel would carry
// the mark through its own DNAT, so a packet destined for a container would be
// routed by the return table and sent straight back out the tunnel it came
// from. That was observed in production and it looks exactly like the service
// being down.
func BuildReturnRuleset(ifaces []string) string {
	var b strings.Builder
	b.WriteString("# generated by failover-backend - do not edit by hand\n")
	b.WriteString("# marks connections arriving from a tunnel so their replies\n")
	b.WriteString("# route back out one, even after a container DNAT has rewritten\n")
	b.WriteString("# their source address.\n\n")

	fmt.Fprintf(&b, "table ip %s\n", NFTReturnTable)
	fmt.Fprintf(&b, "delete table ip %s\n\n", NFTReturnTable)
	fmt.Fprintf(&b, "table ip %s {\n", NFTReturnTable)
	b.WriteString("\tchain prerouting {\n")
	b.WriteString("\t\ttype filter hook prerouting priority mangle; policy accept;\n")

	if len(ifaces) > 0 {
		quoted := make([]string, 0, len(ifaces))
		for _, i := range ifaces {
			quoted = append(quoted, fmt.Sprintf("%q", i))
		}
		// `ct direction original` is load-bearing, not decoration. Without it
		// this also stamps connections the backend *started* down the tunnel -
		// the egress feature's traffic - because their replies arrive on a
		// tunnel too. Those would then have the return mark restored below,
		// get routed by table 100, and be sent straight back out the tunnel
		// instead of to the container that is waiting for them. Only a
		// connection whose first packet arrived from a tunnel is one whose
		// replies belong back down it.
		fmt.Fprintf(&b, "\t\tiifname { %s } ct direction original ct mark set %#x\n",
			strings.Join(quoted, ", "), ReturnMark)
	}
	fmt.Fprintf(&b, "\t\tct direction reply meta mark set ct mark\n")

	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return b.String()
}

// ApplyRuleset writes the ruleset to disk and loads it atomically. The file is
// left in place on purpose: it is the readable record of what the agent
// published, and can be reloaded by hand with `nft -f`.
func ApplyRuleset(ctx context.Context, r Runner, stateDir, ruleset string) (string, error) {
	return applyRuleset(ctx, r, filepath.Join(stateDir, "ruleset.nft"), ruleset)
}

// ApplyReturnRuleset loads the backend's marking ruleset.
func ApplyReturnRuleset(ctx context.Context, r Runner, stateDir, ruleset string) (string, error) {
	return applyRuleset(ctx, r, filepath.Join(stateDir, "return.nft"), ruleset)
}

func applyRuleset(ctx context.Context, r Runner, path, ruleset string) (string, error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", fmt.Errorf("state dir: %w", err)
	}
	if err := os.WriteFile(path, []byte(ruleset), 0o644); err != nil {
		return "", fmt.Errorf("write ruleset: %w", err)
	}
	if _, err := r.Run(ctx, "nft", "-f", path); err != nil {
		return path, fmt.Errorf("load ruleset: %w", err)
	}
	return path, nil
}

